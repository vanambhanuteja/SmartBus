"""Builds 02_seed.sql from seed/*.csv. Run: python3 generate_seed.py
Crowd reports are SYNTHETIC (simulated) and marked source='SYNTHETIC'."""
import csv, random
from datetime import datetime, timedelta

random.seed(7)
out = ["-- GENERATED by generate_seed.py. Demo network is illustrative; crowd reports are SYNTHETIC.\n"]
stops = list(csv.DictReader(open("seed/stops.csv")))
routes = list(csv.DictReader(open("seed/routes.csv")))
for s in stops:
    out.append(f"INSERT INTO bus_stops (stop_id,name,latitude,longitude) VALUES ({s['stop_id']},'{s['name'].replace(chr(39), chr(39)*2)}',{s['latitude']},{s['longitude']});")
for r in routes:
    out.append(f"INSERT INTO routes (route_id,route_code,name) VALUES ({r['route_id']},'{r['route_code']}','{r['name']}');")
    for i, sid in enumerate(r["stop_ids"].split(";"), 1):
        out.append(f"INSERT INTO route_stops (route_id,stop_id,stop_sequence) VALUES ({r['route_id']},{sid},{i});")
out.append("SELECT setval('bus_stops_stop_id_seq',(SELECT max(stop_id) FROM bus_stops));")
out.append("SELECT setval('routes_route_id_seq',(SELECT max(route_id) FROM routes));")
# 2 buses per route (fictional registrations, capacity 50)
bus_id = 0
for r in routes:
    for k in (1, 2):
        bus_id += 1
        out.append(f"INSERT INTO buses (bus_id,registration,capacity) VALUES ({bus_id},'DEMO-{int(r['route_id']):02d}-{k}',50);")
out.append(f"SELECT setval('buses_bus_id_seq',{bus_id});")

def level(p):
    return "LOW" if p <= 30 else "MODERATE" if p <= 60 else "HIGH" if p <= 85 else "OVERCROWDED"

base = datetime(2026, 8, 3)  # a Monday
trip_id = rep_id = 0
for r in routes:
    rid = int(r["route_id"])
    for day in range(3):
        for hour in (8, 9, 13, 18):
            for k in (1, 2):
                trip_id += 1
                dep = base + timedelta(days=day, hours=hour, minutes=15 * k)
                out.append(f"INSERT INTO trips (trip_id,route_id,bus_id,departure_time) VALUES ({trip_id},{rid},{(rid - 1) * 2 + k},'{dep:%Y-%m-%d %H:%M}');")
                p = max(0, min(100, int(random.gauss(80 if hour in (9, 18) else 45, 12))))
                out.append(f"INSERT INTO crowd_reports (trip_id,route_id,occupancy_percent,crowd_level,source,reported_at) VALUES ({trip_id},{rid},{p},'{level(p)}','SYNTHETIC','{dep:%Y-%m-%d %H:%M}');")
out.append(f"SELECT setval('trips_trip_id_seq',{trip_id});")
open("02_seed.sql", "w").write("\n".join(out) + "\n")
print(f"02_seed.sql: {len(stops)} stops, {len(routes)} routes, {bus_id} buses, {trip_id} trips/synthetic reports")
